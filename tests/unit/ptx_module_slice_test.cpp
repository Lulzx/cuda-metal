// slice_module_for_entry: the JIT lowers one entry from a module that can hold
// hundreds. The slice must keep everything the entry can reach, and nothing it
// cannot, without rewriting a byte of what it keeps.
#include "cumetal/ptx/parser.h"

#include <cstdio>
#include <string>

namespace {

int failures = 0;

void expect(bool ok, const char* what) {
    if (!ok) {
        std::fprintf(stderr, "FAIL: %s\n", what);
        ++failures;
    }
}

bool has(const std::string& text, const char* needle) {
    return text.find(needle) != std::string::npos;
}

const char* kModule = R"PTX(//
// Generated by LLVM NVPTX Back-End
//

.version 7.0
.target sm_80
.address_size 64

	// .globl	k
.extern .func (.param .b32 func_retval0) vprintf
(
	.param .b64 vprintf_param_0,
	.param .b64 vprintf_param_1
)
;
.global .align 4 .b8 table[8] = {1, 2, 3, 4, 5, 6, 7, 8};
.global .align 8 .u64 vtable[2] = {generic(via_vtable), 0};
.const .align 4 .b8 coeffs[4];
/* a block comment with braces { } and a semicolon ; and .entry fake( */
.weak .func  (.param .align 2 .b8 func_retval0[2]) leaf(
	.param .b32 leaf_param_0
)
{
	.reg .b16 	%rs<2>;
	// a line comment mentioning unreachable_fn and }
	st.param.b16 	[func_retval0], %rs1;
	ret;
}
.func middle(
	.param .b64 middle_param_0
)
{
	.reg .b32 	%r<2>;
	{ // callseq 0, 0
	.param .b32 param0;
	.param .align 2 .b8 retval0[2];
	call.uni (retval0), leaf, (param0);
	} // callseq 0
	ret;
}
.func taken()
{
	ret;
}
.func via_vtable()
{
	ret;
}
.func unreachable_fn()
{
	.pragma "nounroll; } {";
	ret;
}
.func only_from_other()
{
	ret;
}
.visible .entry k(
	.param .u64 k_param_0
)
.maxntid 128, 1, 1
{
	.reg .b64 	%rd<3>;
	mov.u64 	%rd1, taken;
	{ // callseq 1, 0
	.param .b64 param0;
	call.uni middle, (param0);
	} // callseq 1
	ret;
}
.visible .entry k2(
	.param .u64 k2_param_0
)
{
	{ // callseq 2, 0
	call.uni only_from_other, ();
	} // callseq 2
	ret;
}
.visible .entry child(
	.param .u64 child_param_0
)
{
	ret;
}
.visible .entry parent(
	.param .u64 parent_param_0
)
{
	.reg .b64 	%rd<2>;
	mov.u64 	%rd1, child;
	ret;
}
)PTX";

}  // namespace

int main() {
    const std::string module = kModule;
    const std::string slice = cumetal::ptx::slice_module_for_entry(module, "k");
    expect(!slice.empty(), "slice of k is produced");

    expect(has(slice, ".version 7.0"), "keeps .version");
    expect(has(slice, ".target sm_80"), "keeps .target");
    expect(has(slice, ".address_size 64"), "keeps .address_size");
    expect(has(slice, "vprintf"), "keeps extern prototype");
    expect(has(slice, "table[8] = {1, 2, 3, 4, 5, 6, 7, 8};"), "keeps initialized global intact");
    expect(has(slice, ".const .align 4 .b8 coeffs[4];"), "keeps const declaration");
    expect(has(slice, ".visible .entry k("), "keeps the requested entry");
    expect(has(slice, ".maxntid 128, 1, 1"), "keeps entry properties");
    expect(has(slice, ".func middle("), "keeps directly called function");
    expect(has(slice, ") leaf("), "keeps transitively called function");
    expect(has(slice, ".func taken()"), "keeps function whose address is taken");
    expect(has(slice, ".func via_vtable()"), "keeps function named by a global initializer");
    expect(!has(slice, ".entry k2("), "drops other entries");
    expect(!has(slice, ".func only_from_other()"), "drops functions only another entry reaches");
    expect(!has(slice, ".func unreachable_fn()"), "drops unreachable function (comment mention is not a use)");

    // The slice must still parse as a module with exactly the one entry.
    const auto parsed = cumetal::ptx::parse_ptx(slice);
    expect(parsed.ok, "slice parses");
    expect(parsed.module.entries.size() == 1 && parsed.module.entries[0].name == "k",
           "slice holds exactly entry k");
    expect(parsed.module.version_major == 7 && parsed.module.target == "sm_80",
           "slice keeps module header");

    // An entry whose name is a prefix of another must not pick up the other.
    const std::string slice2 = cumetal::ptx::slice_module_for_entry(module, "k2");
    expect(has(slice2, ".visible .entry k2(") && !has(slice2, ".visible .entry k("),
           "k2 slice holds k2 only");
    expect(has(slice2, ".func only_from_other()") && !has(slice2, ".func middle("),
           "k2 slice follows k2's own calls");

    // A parent that enqueues a child kernel names the child's entry symbol.
    const std::string parent = cumetal::ptx::slice_module_for_entry(module, "parent");
    expect(has(parent, ".visible .entry parent(") && has(parent, ".visible .entry child("),
           "parent slice keeps the child entry it names");
    expect(!has(parent, ".visible .entry k(") && !has(parent, ".visible .entry k2("),
           "parent slice drops unrelated entries");
    expect(!has(slice, ".visible .entry child("), "k slice does not pick up the child entry");

    expect(cumetal::ptx::slice_module_for_entry(module, "missing").empty(),
           "unknown entry yields empty slice");
    expect(cumetal::ptx::slice_module_for_entry(module, "").empty(), "empty name yields empty slice");
    expect(cumetal::ptx::slice_module_for_entry(".version 7.0\n.visible .entry k()\n{\n ret;\n",
                                                "k").empty(),
           "unbalanced module yields empty slice");
    expect(cumetal::ptx::slice_module_for_entry(".version 7.0\n}\n", "k").empty(),
           "stray close brace yields empty slice");

    if (failures != 0) return 1;
    std::printf("PASS: PTX module slicing\n");
    return 0;
}
